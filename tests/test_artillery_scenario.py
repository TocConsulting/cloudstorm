"""
Tests for the Artillery scenario generated by cloudstorm/tools/artillery/run.sh.
"""
import json
import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

RUN_SH = Path(__file__).parent.parent / "cloudstorm" / "tools" / "artillery" / "run.sh"

pytestmark = pytest.mark.skipif(shutil.which("node") is None, reason="node is not installed")


def _generator_source() -> str:
    text = RUN_SH.read_text()
    match = re.search(r'^node -e "\n(.*?)^"$', text, re.DOTALL | re.MULTILINE)
    assert match, "scenario generator not found in run.sh"
    return match.group(1)


def _generate(tmp_path, **env):
    base = {
        "PATH": os.environ["PATH"],
        "TARGET_URL": "https://example.test",
        "USERS": "5000",
        "RAMP_UP": "5",
        "DURATION_SECONDS": "120",
        "ENDPOINTS": "/",
    }
    base.update({k: str(v) for k, v in env.items()})
    subprocess.run(["node", "-e", _generator_source()], cwd=tmp_path, env=base, check=True,
                   capture_output=True)
    return json.loads((tmp_path / "config.json").read_text())


class TestArtilleryScenario:
    def test_arrival_rate_is_capped(self, tmp_path):
        config = _generate(tmp_path, USERS=60000)
        phase = config["config"]["phases"][0]
        assert phase["arrivalRate"] <= 400
        assert phase["maxVusers"] == 60000

    def test_ramp_reaches_all_users(self, tmp_path):
        config = _generate(tmp_path, USERS=100000)
        phase = config["config"]["phases"][0]
        assert phase["arrivalRate"] * phase["duration"] >= 100000

    def test_ramp_follows_spawn_rate_when_slower(self, tmp_path):
        config = _generate(tmp_path, USERS=1000, RAMP_UP=20)
        phase = config["config"]["phases"][0]
        assert phase["duration"] == 20

    def test_request_rate_per_instance_is_capped(self, tmp_path):
        config = _generate(tmp_path, USERS=6250)
        loop = config["scenarios"][0]["flow"][0]
        think = [step["think"] for step in loop["loop"] if "think" in step][0]
        assert 6250 / think <= 300

    def test_users_hold_for_the_whole_duration(self, tmp_path):
        config = _generate(tmp_path, USERS=6250, DURATION_SECONDS=120)
        loop = config["scenarios"][0]["flow"][0]
        think = [step["think"] for step in loop["loop"] if "think" in step][0]
        assert loop["count"] == max(1, 120 // think)

    def test_every_endpoint_is_requested_each_cycle(self, tmp_path):
        config = _generate(tmp_path, ENDPOINTS="/,/api,/login")
        loop = config["scenarios"][0]["flow"][0]["loop"]
        urls = [step["get"]["url"] for step in loop if "get" in step]
        assert urls == ["/", "/api", "/login"]

    def test_caps_can_be_overridden(self, tmp_path):
        config = _generate(tmp_path, USERS=10000, ARTILLERY_MAX_ARRIVAL=1000, ARTILLERY_MAX_RPS=1000)
        phase = config["config"]["phases"][0]
        assert phase["arrivalRate"] == 1000
        loop = config["scenarios"][0]["flow"][0]
        think = [step["think"] for step in loop["loop"] if "think" in step][0]
        assert think == 10
